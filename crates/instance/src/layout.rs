/// Create one instance atomically from a verified release.
///
/// The instance is visible only after every file is written and the staging
/// directory is renamed. A repeated identical request converges; a different
/// record at the same id is a conflict. Stale staging directories for this id
/// are removed first, so an interrupted create never leaves a half-visible
/// instance.
pub fn create(request: CreateRequest) -> Result<CreateOutcome, InstanceError> {
    validate_id(&request.id)?;
    let root = absolute(&request.root)?;
    std::fs::create_dir_all(&root).map_err(storage)?;
    set_mode(&root, 0o700)?;
    cleanup_staging(&root, &request.id)?;

    let paths = InstancePaths::new(&root, &request.id);
    if paths.dir.exists() {
        let existing = load_record(&paths)?;
        if existing.artifact_digest == expected_digest(&request.release)
            || existing.release_dir == canonical(&request.release)?
        {
            let state = load_state(&paths)?;
            if state.lifecycle == "configuring" && state.pid.is_none() {
                // A create that was interrupted after the atomic rename is
                // still a complete record; keep it and let start decide.
            }
            return Ok(CreateOutcome {
                record: existing,
                created: false,
            });
        }
        return Err(InstanceError::new(
            "instance.conflict",
            format!(
                "instance '{}' already exists for another release; choose another id",
                request.id
            ),
        ));
    }

    let release_dir = canonical(&request.release)?;
    let installed = load_release(&release_dir)?;
    let stage = root.join(format!(
        "{STAGING_PREFIX}{}-{}",
        request.id,
        uuid::Uuid::new_v4().simple()
    ));
    std::fs::create_dir_all(&stage).map_err(storage)?;
    set_mode(&stage, 0o700)?;
    let guard = StageGuard {
        path: stage.clone(),
    };

    let data_dir = stage.join("state");
    let workspace = match &request.workspace {
        Some(path) => absolute(path)?,
        None => stage.join("workspace"),
    };
    std::fs::create_dir_all(&data_dir).map_err(storage)?;
    std::fs::create_dir_all(&workspace).map_err(storage)?;
    let final_data = paths.dir.join("state");
    let final_workspace = if request.workspace.is_some() {
        workspace.clone()
    } else {
        paths.dir.join("workspace")
    };
    let final_config = if request.config.is_some() {
        None
    } else {
        Some(paths.dir.join("worker.toml"))
    };

    let mut seed_paths = Vec::new();
    for seed in &installed.seeds {
        validate_relative(&seed.path)?;
        let source = release_dir.join("seeds").join(&seed.path);
        let bytes = std::fs::read(&source).map_err(|_| {
            InstanceError::new(
                "instance.release_invalid",
                format!("seed '{}' is missing from the verified release", seed.path),
            )
        })?;
        if common::bytes_digest(&bytes) != seed.digest {
            return Err(InstanceError::new(
                "instance.release_invalid",
                format!("seed '{}' no longer matches its signed digest", seed.path),
            ));
        }
        let destination = stage.join(&seed.path);
        if !destination.exists() {
            if let Some(parent) = destination.parent() {
                std::fs::create_dir_all(parent).map_err(storage)?;
            }
            write_file(&destination, &bytes, 0o644)?;
        }
        seed_paths.push(seed.path.clone());
    }

    let token = request
        .token
        .clone()
        .or_else(|| request.config.as_deref().and_then(configuration_token))
        .unwrap_or_else(|| uuid::Uuid::new_v4().simple().to_string());
    write_file(&stage.join("token"), token.as_bytes(), 0o600)?;

    let config_path = match &request.config {
        Some(path) => canonical(path).map_err(|_| {
            InstanceError::new(
                "instance.config_invalid",
                "operator configuration file is missing or unreadable",
            )
        })?,
        None => stage.join("worker.toml"),
    };
    let generated_config = request.config.is_none();
    if generated_config {
        let agent = request
            .default_agent
            .clone()
            .unwrap_or_else(|| default_agent(&stage, &installed.registered));
        let text = generated_config_text(&stage, &request, &agent, &token);
        write_file(&config_path, text.as_bytes(), 0o600)?;
    }
    let effective_data = if generated_config {
        data_dir.clone()
    } else {
        configuration_storage(&config_path).unwrap_or(data_dir.clone())
    };

    let record = InstanceRecord {
        schema: RECORD_SCHEMA,
        id: request.id.clone(),
        package: installed.package.clone(),
        version: installed.version.clone(),
        artifact_digest: installed.artifact_digest.clone(),
        binary_digest: common::bytes_digest(&std::fs::read(&installed.binary).map_err(storage)?),
        signer: installed.signer.clone(),
        release_dir: release_dir.clone(),
        binary: installed.binary.clone(),
        config_path: final_config.clone().unwrap_or_else(|| config_path.clone()),
        generated_config,
        data_dir: if generated_config {
            final_data.clone()
        } else {
            effective_data.clone()
        },
        workspace_root: final_workspace.clone(),
        workspace_write: !request.read_only,
        grants: request.grants.clone(),
        limits: request.limits,
        secret_refs: request.secret_refs.clone(),
        seed_assets: seed_paths,
        created_at: now_ms(),
    };
    let state = InstanceState {
        schema: STATE_SCHEMA,
        lifecycle: "configuring".into(),
        pid: None,
        incarnation: None,
        active_profile: None,
        addr: None,
        started_at: None,
        stopped_at: None,
        last_error: None,
        trust: None,
    };
    write_json(&stage.join("instance.json"), &record, 0o600)?;
    write_json(&stage.join("state.json"), &state, 0o600)?;
    sync_tree(&stage)?;
    std::fs::rename(&stage, &paths.dir).map_err(storage)?;
    sync_dir(&root)?;
    drop(guard);
    Ok(CreateOutcome {
        record,
        created: true,
    })
}

/// Inspect one instance without mutating its lifecycle record.
pub fn inspect(root: &Path, id: &str) -> Result<Inspection, InstanceError> {
    validate_id(id)?;
    let root = absolute(root)?;
    let paths = InstancePaths::new(&root, id);
    let record = load_record(&paths)?;
    let mut state = load_state(&paths)?;
    let alive = state
        .pid
        .is_some_and(|pid| process::process_matches(pid, &record.config_path));
    if state.lifecycle == "running" && state.pid.is_some() && !alive {
        state.lifecycle = "faulted".into();
        if state.last_error.is_none() {
            state.last_error = Some("process exited without a stop request".into());
        }
    }

    let base = state.addr.as_ref().map(|addr| format!("http://{addr}"));
    let mut process_health = match state.pid {
        Some(_) if alive => "running".to_string(),
        Some(_) => "exited".to_string(),
        None if matches!(state.lifecycle.as_str(), "stopped" | "faulted") => "exited".to_string(),
        None => "unknown".to_string(),
    };
    let mut runtime_phase = None;
    let mut capacity: Option<InstanceCapacity> = None;
    let mut incarnation = state.incarnation.clone();
    if let Some(base) = &base {
        if let Ok(health) = process::get_json(&format!("{base}/v1/health"), None) {
            process_health = "running".into();
            if let Some(value) = health.get("incarnation").and_then(|value| value.as_str()) {
                incarnation = Some(value.to_string());
            }
            let token = read_token(&paths, &record.config_path);
            if let Ok(status) = process::get_json(&format!("{base}/v1/status"), token.as_deref()) {
                runtime_phase = status
                    .get("phase")
                    .and_then(|value| value.as_str())
                    .map(str::to_string);
                if let Some(value) = status.get("capacity") {
                    capacity = serde_json::from_value(value.clone()).ok();
                }
            }
        } else if alive {
            process_health = "unknown".into();
        }
    }
    let task_activity = match &capacity {
        Some(capacity) if capacity.active == 0 && capacity.queued == 0 => "idle".to_string(),
        Some(_) => "executing".to_string(),
        None => "unknown".to_string(),
    };

    Ok(Inspection {
        instance: record.id,
        package: record.package,
        version: record.version,
        signer: record.signer,
        artifact_digest: record.artifact_digest,
        binary_digest: record.binary_digest,
        release_dir: record.release_dir,
        binary: record.binary,
        config_path: record.config_path,
        data_dir: record.data_dir,
        workspace_root: record.workspace_root,
        workspace_write: record.workspace_write,
        grants: record.grants,
        limits: record.limits,
        secret_refs: record.secret_refs,
        seed_assets: record.seed_assets,
        process_health,
        lifecycle: state.lifecycle,
        task_activity,
        addr: state.addr.clone(),
        runtime_phase,
        incarnation,
        active_profile: state.active_profile,
        pid: state.pid,
        capacity,
        last_error: state.last_error,
        trust: state.trust,
        operator_config: !record.generated_config,
    })
}

/// Proxy one `profile` command to the installed binary and record the active
/// profile name on success.
pub fn profile(root: &Path, id: &str, args: &[String]) -> Result<ProfileOutcome, InstanceError> {
    validate_id(id)?;
    let root = absolute(root)?;
    let paths = InstancePaths::new(&root, id);
    let record = load_record(&paths)?;
    let mut state = load_state(&paths)?;
    crate::trust::enforce(&state)?;
    let mut command = Command::new(&record.binary);
    command
        .arg("profile")
        .args(args)
        .arg("--config")
        .arg(&record.config_path)
        .current_dir(paths.dir.clone());
    let output = command.output().map_err(storage)?;
    let stdout = String::from_utf8_lossy(&output.stdout).to_string();
    let stderr = String::from_utf8_lossy(&output.stderr).to_string();
    let status = output.status.code().unwrap_or(1);
    if status == 0 {
        let subcommand = args
            .iter()
            .find(|arg| !arg.starts_with('-'))
            .map(String::as_str)
            .unwrap_or("");
        let name = args
            .iter()
            .skip_while(|arg| arg.as_str() != subcommand)
            .nth(1)
            .cloned();
        let activate = args.iter().any(|arg| arg == "--activate");
        match subcommand {
            "activate" => state.active_profile = name,
            "create" | "revise" if activate => state.active_profile = name,
            "deactivate" => state.active_profile = None,
            "delete" if state.active_profile == name => state.active_profile = None,
            _ => {}
        }
        write_json(&paths.state, &state, 0o600)?;
    }
    Ok(ProfileOutcome {
        status,
        stdout,
        stderr,
        active_profile: state.active_profile,
    })
}

pub(crate) fn load_record(paths: &InstancePaths) -> Result<InstanceRecord, InstanceError> {
    read_json(&paths.record).map_err(|_| {
        InstanceError::new(
            "instance.not_found",
            format!(
                "instance '{}' has no readable instance.json",
                paths.dir.display()
            ),
        )
    })
}

pub(crate) fn load_state(paths: &InstancePaths) -> Result<InstanceState, InstanceError> {
    read_json(&paths.state).map_err(|_| {
        InstanceError::new(
            "instance.state_invalid",
            format!(
                "instance '{}' has no readable state.json",
                paths.dir.display()
            ),
        )
    })
}

pub(crate) fn save_state(
    paths: &InstancePaths,
    state: &InstanceState,
) -> Result<(), InstanceError> {
    write_json(&paths.state, state, 0o600)
}

pub(crate) fn token_for(paths: &InstancePaths, record: &InstanceRecord) -> Option<String> {
    read_token(paths, &record.config_path)
}

pub(crate) fn instance_paths(root: &Path, id: &str) -> Result<InstancePaths, InstanceError> {
    validate_id(id)?;
    Ok(InstancePaths::new(&absolute(root)?, id))
}

fn read_token(paths: &InstancePaths, config: &Path) -> Option<String> {
    if let Ok(value) = std::fs::read_to_string(&paths.token) {
        let value = value.trim().to_string();
        if !value.is_empty() {
            return Some(value);
        }
    }
    let text = std::fs::read_to_string(config).ok()?;
    let value: toml::Value = toml::from_str(&text).ok()?;
    value
        .get("token")
        .and_then(toml::Value::as_str)
        .map(str::to_string)
}

fn configuration_token(config: &Path) -> Option<String> {
    let text = std::fs::read_to_string(config).ok()?;
    let value: toml::Value = toml::from_str(&text).ok()?;
    value
        .get("token")
        .and_then(toml::Value::as_str)
        .map(str::to_string)
}

fn configuration_storage(config: &Path) -> Option<PathBuf> {
    let text = std::fs::read_to_string(config).ok()?;
    let value: toml::Value = toml::from_str(&text).ok()?;
    let directory = value.get("storage")?.get("directory")?.as_str()?;
    let path = PathBuf::from(directory);
    if path.is_absolute() {
        Some(path)
    } else {
        config.parent().map(|parent| parent.join(path))
    }
}

pub(crate) fn load_release(directory: &Path) -> Result<install::Installed, InstanceError> {
    let digest_dir = directory
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or("");
    let packages = directory.parent();
    let cache = packages.and_then(Path::parent);
    let valid = packages.and_then(Path::file_name) == Some(std::ffi::OsStr::new("sha256"))
        && cache.and_then(Path::file_name) == Some(std::ffi::OsStr::new("packages"))
        && digest_dir.len() == 64;
    if !valid {
        return Err(InstanceError::new(
            "instance.release_invalid",
            "release must be a verified cache directory under packages/sha256/<digest>",
        ));
    }
    let root = cache.and_then(Path::parent).ok_or_else(|| {
        InstanceError::new("instance.release_invalid", "release cache root is invalid")
    })?;
    let installed = Installer::new(root, TrustPolicy::default()).installed()?;
    let expected = format!("sha256:{digest_dir}");
    installed
        .into_iter()
        .find(|release| release.artifact_digest == expected)
        .ok_or_else(|| {
            InstanceError::new(
                "instance.release_invalid",
                "release is not present in the verified cache",
            )
        })
}

fn expected_digest(release: &Path) -> String {
    release
        .file_name()
        .and_then(|name| name.to_str())
        .map(|name| format!("sha256:{name}"))
        .unwrap_or_default()
}

fn default_agent(stage: &Path, registered: &[String]) -> String {
    let agents = stage.join("assets").join("agents");
    if let Ok(entries) = std::fs::read_dir(&agents) {
        let mut names: Vec<String> = entries
            .filter_map(Result::ok)
            .filter(|entry| entry.path().extension().is_some_and(|ext| ext == "toml"))
            .filter_map(|entry| std::fs::read_to_string(entry.path()).ok())
            .filter_map(|text| toml::from_str::<toml::Value>(&text).ok())
            .filter_map(|value| {
                value
                    .get("name")
                    .and_then(toml::Value::as_str)
                    .map(str::to_string)
            })
            .collect();
        names.sort();
        if let Some(name) = names.into_iter().next() {
            return name;
        }
    }
    if registered.iter().any(|id| id == "manual") {
        return "manual".into();
    }
    registered
        .first()
        .cloned()
        .unwrap_or_else(|| "general".into())
}

fn generated_config_text(
    stage: &Path,
    request: &CreateRequest,
    agent: &str,
    token: &str,
) -> String {
    let mut text = String::new();
    text.push_str(&format!("instance = {}\n", quote(&request.id)));
    text.push_str("namespace = \"local\"\n");
    text.push_str(&format!("default_agent = {}\n", quote(agent)));
    text.push_str(&format!("token = {}\n", quote(token)));
    text.push_str(&format!(
        "token_scopes = [{}]\n",
        quote_list(&request.grants)
    ));
    text.push_str(&format!("grants = [{}]\n", quote_list(&request.grants)));
    text.push_str(&format!(
        "max_active = {}\n",
        request.limits.max_active.max(1)
    ));
    text.push_str(&format!("max_queue = {}\n", request.limits.max_queue));
    text.push_str(&format!(
        "per_principal = {}\n",
        request.limits.per_principal.max(1)
    ));
    // A seedless release still starts with its compiled manual agent; only
    // asset directories materialized from the verified seed catalog are
    // declared.
    let mut paths = Vec::new();
    for name in ["agents", "prompts", "skills"] {
        let relative = format!("assets/{name}");
        if stage.join(&relative).is_dir() {
            paths.push((name, relative));
        }
    }
    if !paths.is_empty() {
        text.push_str("\n[paths]\n");
        for (key, value) in paths {
            text.push_str(&format!("{key} = {}\n", quote(&value)));
        }
    }
    text.push_str("\n[storage]\ndirectory = \"state\"\n");
    text
}

fn quote(value: &str) -> String {
    let escaped = value.replace('\\', "\\\\").replace('"', "\\\"");
    format!("\"{escaped}\"")
}

fn quote_list(values: &[String]) -> String {
    values
        .iter()
        .map(|value| quote(value))
        .collect::<Vec<_>>()
        .join(", ")
}

pub(crate) fn validate_id(id: &str) -> Result<(), InstanceError> {
    let valid = !id.is_empty()
        && id.len() <= 64
        && id
            .chars()
            .next()
            .is_some_and(|first| first.is_ascii_alphanumeric())
        && id
            .chars()
            .all(|character| character.is_ascii_alphanumeric() || "._-".contains(character))
        && !id.contains("..");
    if !valid {
        return Err(InstanceError::new(
            "instance.id_invalid",
            "instance id must be 1-64 characters of letters, digits, '.', '_' or '-'",
        ));
    }
    Ok(())
}

fn validate_relative(path: &str) -> Result<(), InstanceError> {
    let valid = !path.is_empty()
        && !path.starts_with('/')
        && !path.contains('\\')
        && Path::new(path)
            .components()
            .all(|component| matches!(component, Component::Normal(_)));
    if !valid {
        return Err(InstanceError::new(
            "instance.release_invalid",
            format!("seed path '{path}' is not relative to the instance root"),
        ));
    }
    Ok(())
}

fn cleanup_staging(root: &Path, id: &str) -> Result<(), InstanceError> {
    let prefix = format!("{STAGING_PREFIX}{id}-");
    let entries = match std::fs::read_dir(root) {
        Ok(entries) => entries,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(error) => return Err(storage(error)),
    };
    for entry in entries {
        let entry = entry.map_err(storage)?;
        if entry.file_name().to_string_lossy().starts_with(&prefix) {
            std::fs::remove_dir_all(entry.path()).map_err(storage)?;
        }
    }
    Ok(())
}

fn absolute(path: &Path) -> Result<PathBuf, InstanceError> {
    let path = if path.is_absolute() {
        path.to_path_buf()
    } else {
        std::env::current_dir().map_err(storage)?.join(path)
    };
    Ok(canonical_or_self(&path))
}

fn canonical(path: &Path) -> Result<PathBuf, InstanceError> {
    std::fs::canonicalize(path).map_err(|_| {
        InstanceError::new(
            "instance.path_unavailable",
            format!("path '{}' is not readable", path.display()),
        )
    })
}

fn canonical_or_self(path: &Path) -> PathBuf {
    std::fs::canonicalize(path).unwrap_or_else(|_| path.to_path_buf())
}

pub(crate) fn write_json<T: Serialize>(
    path: &Path,
    value: &T,
    mode: u32,
) -> Result<(), InstanceError> {
    let bytes = serde_json::to_vec_pretty(value)
        .map_err(|error| InstanceError::new("instance.storage_unavailable", error.to_string()))?;
    write_file(path, &bytes, mode)
}

pub(crate) fn write_file(path: &Path, bytes: &[u8], mode: u32) -> Result<(), InstanceError> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(storage)?;
    }
    let temporary = path.with_extension(format!(
        "tmp-{}-{}",
        std::process::id(),
        uuid::Uuid::new_v4().simple()
    ));
    {
        let mut file = std::fs::File::create(&temporary).map_err(storage)?;
        file.write_all(bytes).map_err(storage)?;
        file.sync_all().map_err(storage)?;
    }
    set_mode(&temporary, mode)?;
    std::fs::rename(&temporary, path).map_err(storage)?;
    if let Some(parent) = path.parent() {
        sync_dir(parent)?;
    }
    Ok(())
}

pub(crate) fn read_json<T: for<'de> Deserialize<'de>>(path: &Path) -> Result<T, ()> {
    let bytes = std::fs::read(path).map_err(|_| ())?;
    serde_json::from_slice(&bytes).map_err(|_| ())
}

fn sync_tree(path: &Path) -> Result<(), InstanceError> {
    for entry in std::fs::read_dir(path).map_err(storage)? {
        let entry = entry.map_err(storage)?;
        if entry.file_type().map_err(storage)?.is_dir() {
            sync_tree(&entry.path())?;
        } else if let Ok(file) = std::fs::File::open(entry.path()) {
            file.sync_all().map_err(storage)?;
        }
    }
    sync_dir(path)
}

fn sync_dir(path: &Path) -> Result<(), InstanceError> {
    #[cfg(unix)]
    {
        std::fs::File::open(path)
            .and_then(|file| file.sync_all())
            .map_err(storage)?;
    }
    Ok(())
}

pub(crate) fn set_mode(path: &Path, mode: u32) -> Result<(), InstanceError> {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(path, std::fs::Permissions::from_mode(mode)).map_err(storage)?;
    }
    let _ = mode;
    Ok(())
}

fn storage(error: std::io::Error) -> InstanceError {
    InstanceError::new(
        "instance.storage_unavailable",
        format!("instance storage operation failed: {error}"),
    )
}

fn now_ms() -> i64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|duration| duration.as_millis() as i64)
        .unwrap_or(0)
}

struct StageGuard {
    path: PathBuf,
}

impl Drop for StageGuard {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.path);
    }
}

