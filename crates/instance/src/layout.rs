//! Instance host layout, atomic creation, inspection, and profile proxying.
//!
//! `instance.json` is host-owned metadata. `state.json` is the local lifecycle
//! record written only by this tool. The generated `worker.toml` is operator
//! editable and is never rewritten by start/stop. Secrets stay in `token`
//! (mode 0600) or the operator's configuration; `instance.json` never carries
//! a secret value.

use install::{InstallError, Installer, TrustPolicy};
use serde::{Deserialize, Serialize};
use std::fmt;
use std::io::Write;
use std::path::{Component, Path, PathBuf};
use std::process::Command;

use crate::process;
use std::time::{SystemTime, UNIX_EPOCH};

const RECORD_SCHEMA: u32 = 1;
const STATE_SCHEMA: u32 = 1;
const STAGING_PREFIX: &str = ".staging-";

/// Stable error code and redaction-safe message for instance operations.
#[derive(Debug, Clone)]
pub struct InstanceError {
    /// Stable code such as `instance.not_found`.
    pub code: String,
    /// Actionable message without secret values.
    pub message: String,
}

impl InstanceError {
    /// Construct one instance error.
    pub fn new(code: impl Into<String>, message: impl Into<String>) -> Self {
        Self {
            code: code.into(),
            message: message.into(),
        }
    }
}

impl fmt::Display for InstanceError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(formatter, "{}: {}", self.code, self.message)
    }
}

impl std::error::Error for InstanceError {}

impl From<InstallError> for InstanceError {
    fn from(error: InstallError) -> Self {
        Self::new(error.code, error.message)
    }
}

/// Resource ceilings recorded for one instance.
#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
pub struct InstanceLimits {
    /// Active execution ceiling.
    pub max_active: usize,
    /// Pending queue ceiling.
    pub max_queue: usize,
    /// Per-principal admitted work ceiling.
    pub per_principal: usize,
}

impl Default for InstanceLimits {
    fn default() -> Self {
        Self {
            max_active: 4,
            max_queue: 32,
            per_principal: 8,
        }
    }
}

/// Last explicit trust decision for one installed instance.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TrustStatus {
    /// `continue`, `restrict`, or `quarantine`.
    pub decision: install::InstalledAction,
    /// Redacted operator-facing reason.
    pub reason: String,
    /// Advisory generation used for the decision.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub advisory_generation: Option<u64>,
    /// Millisecond Unix decision time.
    pub decided_at: i64,
}

/// Host-owned record for one instance.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct InstanceRecord {
    /// Record schema.
    pub schema: u32,
    /// Stable instance identity.
    pub id: String,
    /// Package name.
    pub package: String,
    /// Package version.
    pub version: String,
    /// Immutable release manifest digest.
    pub artifact_digest: String,
    /// Executable digest.
    pub binary_digest: String,
    /// Trusted signer identity bound to the installed release.
    #[serde(default)]
    pub signer: String,
    /// Verified release directory.
    pub release_dir: PathBuf,
    /// Executable inside the verified release.
    pub binary: PathBuf,
    /// Operator-selected or generated configuration file.
    pub config_path: PathBuf,
    /// Whether `config_path` was generated by this tool.
    pub generated_config: bool,
    /// Durable Worker data directory.
    pub data_dir: PathBuf,
    /// Authorized workspace root.
    pub workspace_root: PathBuf,
    /// Whether the workspace is writable by this instance.
    pub workspace_write: bool,
    /// Instance grants intersected with profiles and principals.
    pub grants: Vec<String>,
    /// Resource ceilings.
    pub limits: InstanceLimits,
    /// Credential references. Never secret values.
    pub secret_refs: Vec<String>,
    /// Seed asset paths materialized for this instance.
    pub seed_assets: Vec<String>,
    /// Creation time in milliseconds since the Unix epoch.
    pub created_at: i64,
}

/// Local lifecycle state distinct from process health and task activity.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct InstanceState {
    /// State schema.
    pub schema: u32,
    /// `configuring`, `running`, `upgrading`, `stopped`, `faulted`, or
    /// `quarantined`.
    pub lifecycle: String,
    /// Recorded process id when started.
    #[serde(default)]
    pub pid: Option<u32>,
    /// Process incarnation reported by the Worker.
    #[serde(default)]
    pub incarnation: Option<String>,
    /// Active profile name, if any.
    #[serde(default)]
    pub active_profile: Option<String>,
    /// Bound listener.
    #[serde(default)]
    pub addr: Option<String>,
    /// Start time in milliseconds since the Unix epoch.
    #[serde(default)]
    pub started_at: Option<i64>,
    /// Stop time in milliseconds since the Unix epoch.
    #[serde(default)]
    pub stopped_at: Option<i64>,
    /// Last redacted lifecycle error.
    #[serde(default)]
    pub last_error: Option<String>,
    /// Last explicit trust decision. Missing means no trust evaluation has
    /// been applied and the instance is not quarantined.
    #[serde(default)]
    pub trust: Option<TrustStatus>,
}

/// Result of an idempotent create request.
#[derive(Debug, Clone)]
pub struct CreateOutcome {
    /// Persisted record.
    pub record: InstanceRecord,
    /// Whether this call created the instance.
    pub created: bool,
}

/// One create request.
#[derive(Debug, Clone)]
pub struct CreateRequest {
    /// Instances root.
    pub root: PathBuf,
    /// Stable instance id.
    pub id: String,
    /// Verified release directory under `<cache>/packages/sha256/<digest>`.
    pub release: PathBuf,
    /// Instance grants.
    pub grants: Vec<String>,
    /// Workspace root. Defaults to `<instance>/workspace`.
    pub workspace: Option<PathBuf>,
    /// Whether the workspace is writable.
    pub read_only: bool,
    /// Resource ceilings.
    pub limits: InstanceLimits,
    /// Credential references.
    pub secret_refs: Vec<String>,
    /// Operator configuration file. Generated when absent.
    pub config: Option<PathBuf>,
    /// Default agent for a generated configuration.
    pub default_agent: Option<String>,
    /// Explicit development token. Generated when absent.
    pub token: Option<String>,
}

impl CreateRequest {
    /// Start a create request for one verified release.
    pub fn new(
        root: impl Into<PathBuf>,
        id: impl Into<String>,
        release: impl Into<PathBuf>,
    ) -> Self {
        Self {
            root: root.into(),
            id: id.into(),
            release: release.into(),
            grants: default_grants(),
            workspace: None,
            read_only: false,
            limits: InstanceLimits::default(),
            secret_refs: Vec::new(),
            config: None,
            default_agent: None,
            token: None,
        }
    }
}

